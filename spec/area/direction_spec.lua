require('spec/setup/busted')()

local Direction = require('__stdlib2__/stdlib/area/direction')

describe('Direction Functions', function()
    local d = defines.direction

    it('exposes all 16 directions', function()
        for name, value in pairs(d) do
            assert.same(value, Direction[name], name)
        end
    end)

    describe('.next', function()
        it('returns the next 4way direction clockwise by default', function()
            assert.same(d.east, Direction.next(d.north))
            assert.same(d.south, Direction.next(d.east))
            assert.same(d.west, Direction.next(d.south))
            assert.same(d.north, Direction.next(d.west))
            assert.same(d.north, Direction.next(d.west, false))
        end)

        it('returns the next 8way direction clockwise when mode is true', function()
            assert.same(d.northeast, Direction.next(d.north, true))
            assert.same(d.north, Direction.next(d.northwest, true))
        end)

        it('returns the next of 16 directions when mode is "16"', function()
            assert.same(d.northnortheast, Direction.next(d.north, '16'))
            assert.same(d.north, Direction.next(d.northnorthwest, '16'))
        end)
    end)

    describe('.previous', function()
        it('goes counter clockwise', function()
            assert.same(d.west, Direction.previous(d.north))
            assert.same(d.northwest, Direction.previous(d.north, true))
            assert.same(d.northnorthwest, Direction.previous(d.north, '16'))
        end)
    end)

    describe('.next_direction (deprecated)', function()
        local nd = Direction.next_direction
        it('returns the next 4way direction', function()
            assert.same(d.east, nd(d.north))
            assert.same(d.north, nd(d.west))
            assert.same(d.west, nd(d.north, true))
        end)
        it('returns the next 8way direction', function()
            assert.same(d.northeast, nd(d.north, false, true))
            assert.same(d.north, nd(d.northwest, false, true))
            assert.same(d.northwest, nd(d.north, true, true))
        end)
    end)

    describe('.direction_to_orientation', function()
        it('should convert a direction to an orientation', function()
            local dto = Direction.direction_to_orientation
            assert.same(0, dto(d.north))
            assert.same(.25, dto(d.east))
            assert.same(.5, dto(d.south))
            assert.same(.75, dto(d.west))
            assert.same(.125, dto(d.northeast))
            assert.same(.375, dto(d.southeast))
            assert.same(.625, dto(d.southwest))
            assert.same(.875, dto(d.northwest))
        end)
    end)

    describe('.opposite_direction', function()
        it('should return the opposite direction', function()
            local od = Direction.opposite_direction
            assert.same(d.west, od(d.east))
            assert.same(d.southwest, od(d.northeast))
            assert.same(d.southsouthwest, od(d.northnortheast))
        end)
    end)

    describe('.orientation_to_4way', function()
        it('should map orientations to the 4 cardinal directions', function()
            assert.same(d.north, Direction.orientation_to_4way(.124))
            assert.same(d.east, Direction.orientation_to_4way(.125))
            assert.same(d.east, Direction.orientation_to_4way(.25))
            assert.same(d.south, Direction.orientation_to_4way(.5))
            assert.same(d.west, Direction.orientation_to_4way(.75))
            assert.same(d.north, Direction.orientation_to_4way(.875))
        end)
    end)

    describe('.orientation_to_8way', function()
        it('should map orientations to 8 directions', function()
            assert.same(d.north, Direction.orientation_to_8way(.06))
            assert.same(d.northeast, Direction.orientation_to_8way(.0625))
            assert.same(d.east, Direction.orientation_to_8way(.25))
            assert.same(d.southwest, Direction.orientation_to_8way(.628))
            assert.same(d.south, Direction.orientation_to_8way(.501))
        end)
    end)

    describe('.to_vector', function()
        it('keeps the vectors of the 8 primary directions', function()
            assert.same({ x = 0, y = -2 }, Direction.to_vector(d.north, 2))
            assert.same({ x = 2, y = -2 }, Direction.to_vector(d.northeast, 2))
            assert.same({ x = 1, y = 0 }, Direction.to_vector(d.east))
            assert.same({ x = -1, y = 1 }, Direction.to_vector(d.southwest))
        end)

        it('returns unit vectors for the secondary directions', function()
            local v = Direction.to_vector(d.northnortheast)
            assert.same(0.382683, v.x)
            assert.same(-0.92388, v.y)
            v = Direction.to_vector(d.westsouthwest, 2)
            assert.same(-1.847759, v.x)
            assert.same(0.765367, v.y)
        end)
    end)
end)
